export function mergeWithCurated(dbProducts: Product[]): Product[] {
  if (!dbProducts || dbProducts.length === 0) {
    return [];
  }
  const byId = new Map<string, Product>();
  for (const c of curatedProducts) {
    byId.set(c.id, c);
  }

  const merged = dbProducts.map((p) => {
    const curated = byId.get(p.id);
    if (!curated) return p;
    const isPreview = p.lead_time?.startsWith('Preview') || p.stock === 0 || p.description?.includes('Collection preview');
    if (isPreview) {
      return {
        ...p,
        name: curated.name,
        description: curated.description,
        price: p.price > 0 ? p.price : curated.price,
        stock: p.stock,
        lead_time: curated.lead_time,
        images: curated.images,
        dimensions: curated.dimensions,
        materials: curated.materials,
        care: curated.care,
        model: p.model || curated.model,
      };
    }
    return {
      ...p,
      dimensions: p.dimensions || curated.dimensions,
      materials: p.materials || curated.materials,
      care: p.care || curated.care,
    };
  });

  return merged;
}
