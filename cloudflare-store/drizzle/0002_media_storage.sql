CREATE TABLE media_files (id TEXT PRIMARY KEY NOT NULL, type TEXT NOT NULL, size INTEGER NOT NULL, chunks INTEGER NOT NULL);
CREATE TABLE media_chunks (file_id TEXT NOT NULL REFERENCES media_files(id) ON DELETE CASCADE, part INTEGER NOT NULL, data TEXT NOT NULL, PRIMARY KEY(file_id,part));
CREATE TRIGGER media_capacity BEFORE INSERT ON media_files
BEGIN
 SELECT CASE WHEN (SELECT COALESCE(SUM(size),0) FROM media_files)+NEW.size>209715200 THEN RAISE(ABORT,'media_capacity') END;
END;
